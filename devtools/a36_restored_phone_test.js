'use strict';
const {chromium}=require('/tmp/fc-a36-restore/node_modules/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true,args:['--autoplay-policy=no-user-gesture-required','--disable-dev-shm-usage']});
 const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:3,isMobile:true,hasTouch:true});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  const file=path.join(process.cwd(),'preview/a36-restored.html');
  await page.goto(pathToFileURL(file).href,{waitUntil:'domcontentloaded',timeout:30000});
  await page.waitForFunction(()=>document.querySelector('#demoPosition')?.textContent.includes('ENTRY 1 OF 5'),{timeout:15000});
  assert.equal(await page.locator('#demoMedia .videoSlide').count(),5,'five dancer slides');
  assert.equal(await page.locator('#demo').isVisible(),true,'full-screen demo visible');
  assert.equal(await page.locator('#profileSheet').count(),0,'rejected profile card absent');
  assert.equal(await page.locator('.demo-banner').count(),0,'rejected debug banner absent');
  assert.equal(await page.locator('#demoPosition').innerText(),'ENTRY 1 OF 5');
  fs.mkdirSync('a36-restored-evidence',{recursive:true});
  await page.screenshot({path:'a36-restored-evidence/iphone-start.png',fullPage:true});
  await page.locator('#demoNext').click();
  assert.equal(await page.locator('#demoPosition').innerText(),'ENTRY 2 OF 5','next dancer works');
  await page.screenshot({path:'a36-restored-evidence/iphone-second.png',fullPage:true});
  await page.locator('#demoVote').click();
  assert.equal(await page.locator('#sheet').isVisible(),true,'ballot opens');
  assert.equal(await page.locator('#sheetBody [data-practice]').count(),5,'ballot shows all five');
  await page.screenshot({path:'a36-restored-evidence/iphone-ballot.png',fullPage:true});
  await page.locator('#sheetBody [data-practice="1"]').click();
  assert.match(await page.locator('#sheetTitle').innerText(),/You made the call/);
  await page.screenshot({path:'a36-restored-evidence/iphone-result.png',fullPage:true});
  // North Star interaction gate: every state below is disconnected SAMPLE DATA.
  // These assertions check the approved journey, not real ballot recording or settlement.
  assert.match(await page.locator('#sheetKicker').innerText(),/EXAMPLE RESULT/);
  await page.locator('#doneDemo').click();
  assert.equal(await page.locator('#feed').isVisible(),true,'demo exits to competition discovery');
  await page.locator('#feedVote').click();
  assert.match(await page.locator('#sheetTitle').innerText(),/Vote in Street Dance Weekend/);
  assert.equal(await page.locator('#sheetBody [data-vote]').count(),2,'sample challenge offers both competitors');
  await page.locator('#sheetBody [data-vote="0"]').click();
  assert.match(await page.locator('#sheetTitle').innerText(),/Your vote is recorded in this prototype/);
  assert.match(await page.locator('#sheetBody').innerText(),/Following a competitor|follow @NyraMoves|Would you also like to follow/i);
  await page.screenshot({path:'a36-restored-evidence/iphone-vote-receipt.png',fullPage:true});
  await page.locator('#notNow').click();
  await page.locator('[data-nav="you"]').click();
  await page.locator('#myVotes').click();
  assert.match(await page.locator('#yourPanel').innerText(),/Street Dance Weekend/,'vote remains available without following');
  assert.match(await page.locator('#yourPanel').innerText(),/@NyraMoves/);
  await page.locator('#myFollowing').click();
  assert.match(await page.locator('#yourPanel').innerText(),/No follows yet/,'vote did not silently follow');
  await page.locator('[data-nav="home"]').click();
  await page.locator('#feedSecondary').click();
  await page.locator('#feedFollowing').click();
  assert.match(await page.locator('#feedTitle').innerText(),/Street Dance Weekend/,'followed competitor discoverable in sample feed');
  await page.locator('[data-nav="you"]').click();
  await page.locator('#myFollowing').click();
  assert.match(await page.locator('#yourPanel').innerText(),/@NyraMoves/,'explicit following appears under You');
  await page.screenshot({path:'a36-restored-evidence/iphone-following.png',fullPage:true});
  await page.locator('#scenario').selectOption('fan');
  assert.match(await page.locator('#feedTitle').innerText(),/Your pick won/,'returning voter sees outcome');
  await page.locator('#feedVote').click();
  assert.match(await page.locator('#sheetTitle').innerText(),/The result is in/);
  assert.match(await page.locator('#sheetKicker').innerText(),/SAMPLE DATA/);
  await page.screenshot({path:'a36-restored-evidence/iphone-returning-voter.png',fullPage:true});
  await page.locator('#sheetClose').click();
  await page.locator('#scenario').selectOption('competitor');
  assert.match(await page.locator('#feedTitle').innerText(),/Your race is close/,'returning competitor sees provisional standing');
  await page.locator('#feedVote').click();
  assert.match(await page.locator('#sheetTitle').innerText(),/Your race is still close/);
  assert.match(await page.locator('#sheetBody').innerText(),/Nothing is decided yet/);
  await page.screenshot({path:'a36-restored-evidence/iphone-returning-competitor.png',fullPage:true});
  const overflow=await page.evaluate(()=>({scrollWidth:document.documentElement.scrollWidth,viewport:document.documentElement.clientWidth}));
  assert.ok(overflow.scrollWidth<=overflow.viewport+1,'no horizontal viewport overflow');
  assert.deepEqual(errors,[],'no JS runtime errors');
  console.log('PASS: A3.5 approved source, 390x844 mobile viewport; five slide navigation, ballot, sample result, no rejected profile page. This is Chromium emulation, NOT a real iPhone test.');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});